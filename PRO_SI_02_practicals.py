def recommend(budget, clothing, occasion, trend_pref,
              comfort_pref, quality_pref, fit_pref):
    # Filter real products from the dataset
    products = df.copy()
    products = products[products["price_usd"] <= budget]

    if clothing != "Any":
        products = products[
            products["clothing_type"].astype(str) == clothing
        ]
    if occasion != "Any":
        products = products[
            products["occasion"].astype(str) == occasion
        ]

    if products.empty:
        return (
            "No matching items found. Try increasing your budget or selecting Any.",
            pd.DataFrame(), "—", "—"
        )

    # Rank products by closeness to the user's preferences.
    # Each score is normalized to the range observed in the dataset.
    prefs = {
        "trend_score": trend_pref,
        "comfort_score": comfort_pref,
        "quality_score": quality_pref,
        "fit_score": fit_pref
    }

    score = pd.Series(0.0, index=products.index)
    used = 0

    for col, pref in prefs.items():
        lo, hi = df[col].min(), df[col].max()
        if pd.notna(lo) and pd.notna(hi) and hi > lo:
            normalized = (products[col] - lo) / (hi - lo)
            target = (pref - lo) / (hi - lo)
            score += 1 - (normalized - target).abs().clip(0, 1)
            used += 1

    products = products.copy()
    products["Style Match (%)"] = (
        100 * score / max(used, 1)
    ).round(1)

    products = products.sort_values(
        "Style Match (%)", ascending=False
    ).head(8)

    # Build predictions for the user's preferred feature combination.
    # These estimate outcomes for a hypothetical matching product.
    row = pd.DataFrame([{
        "price_usd": budget,
        "trend_score": trend_pref,
        "comfort_score": comfort_pref,
        "quality_score": quality_pref,
        "fit_score": fit_pref
    }], columns=features)

    purchase_result = "Model unavailable"
    satisfaction_result = "Model unavailable"

    if purchase_model is not None:
        p = purchase_model.predict_proba(row)[0]
        classes = purchase_model[-1].classes_
        if 1 in classes:
            probability = float(p[list(classes).index(1)])
            purchase_result = f"{probability:.1%} estimated purchase likelihood"

    if satisfaction_model is not None:
        value = float(satisfaction_model.predict(row)[0])
        satisfaction_result = f"{value:.2f} predicted satisfaction score"

    display_cols = [
        c for c in [
            "clothing_type", "occasion", "price_usd",
            "trend_score", "comfort_score", "quality_score",
            "fit_score", "Style Match (%)"
        ] if c in products.columns
    ]

    message = (
        f"Found {len(products)} recommended styles within your budget. "
        "Ranked by similarity to your preferences."
    )

    return (
        message,
        products[display_cols].reset_index(drop=True),
        purchase_result,
        satisfaction_result
    )

