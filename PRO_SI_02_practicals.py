# PRACTICAL 5: CONFIDENCE INTERVAL, Z-TEST AND T-TEST

import pandas as pd
import numpy as np
from scipy import stats

df = pd.read_csv("/content/fashion_dataset_complete.csv")
x = df["price_usd"].dropna()
mu0, alpha, sigma = 100, 0.05, 50

# 95% Confidence Interval
ci = stats.t.interval(0.95, len(x)-1,
                      loc=x.mean(), scale=stats.sem(x))
print("Mean price:", x.mean())
print("95% Confidence Interval:", ci)

# One-sample t-test
t, pt = stats.ttest_1samp(x, mu0)
print("\nT-test statistic:", t, "P-value:", pt)

# One-sample Z-test (assumed known population SD)
z = (x.mean()-mu0)/(sigma/np.sqrt(len(x)))
pz = 2*stats.norm.sf(abs(z))
print("Z-test statistic:", z, "P-value:", pz)

print("H0: Mean price = $100")
print("H1: Mean price is not $100")
print("T-test:", "Reject H0" if pt < alpha else "Fail to reject H0")
print("Z-test:", "Reject H0" if pz < alpha else "Fail to reject H0")

